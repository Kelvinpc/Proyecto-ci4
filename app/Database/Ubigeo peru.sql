CREATE DATABASE IF NOT EXISTS senati DEFAULT CHARACTER SET utf8;
USE SENATI;

CREATE TABLE departamentos
(
	iddepartamento		CHAR(10) 	NOT NULL,
	departamento		VARCHAR(70)	NOT NULL,
	CONSTRAINT pk_iddepartamento_dep PRIMARY KEY (iddepartamento)
)ENGINE = INNODB;


CREATE TABLE provincias
(
	idprovincia			CHAR(10)	NOT NULL,
	iddepartamento		CHAR(10) 	NOT NULL,
	provincia			VARCHAR(70)	NOT NULL,
	CONSTRAINT pk_idprovincia_pro PRIMARY KEY (idprovincia),
	CONSTRAINT fk_iddepartamento_pro FOREIGN KEY (iddepartamento) REFERENCES departamentos (iddepartamento)
)ENGINE = INNODB;


CREATE TABLE distritos
(
	iddistrito			CHAR(10)	NOT NULL,
	idprovincia			CHAR(10)	NOT NULL,
	distrito			VARCHAR(70) NOT NULL,
	ubigeo				CHAR(6)		NOT NULL,
	CONSTRAINT pk_iddistrito_dis PRIMARY KEY (iddistrito),
	CONSTRAINT fk_idprovincia_dis FOREIGN KEY (idprovincia) REFERENCES provincias (idprovincia),
	CONSTRAINT uk_ubigeo_dis UNIQUE (ubigeo)
)ENGINE = INNODB;

-- PROCEDIMIENTOS ALMACENADOS

DELIMITER $$
CREATE PROCEDURE SPU_DEPARTAMENTOS_REGISTRAR(IN _departamento VARCHAR(70))
BEGIN
	DECLARE _iddepartamento CHAR(10);
	SET _iddepartamento = (SELECT CONCAT('DP',RIGHT(CONCAT('0000000000',COUNT(*) + 1),8)) FROM departamentos);
	INSERT INTO departamentos (iddepartamento, departamento) VALUES(_iddepartamento, _departamento);
END $$


DELIMITER $$
CREATE PROCEDURE SPU_PROVINCIAS_REGISTRAR
(
	IN _iddepartamento 	CHAR(10),
	IN _provincia		VARCHAR(70)
)
BEGIN
	DECLARE _idprovincia CHAR(10);
	SET _idprovincia = (SELECT CONCAT('PR',RIGHT(CONCAT('0000000000',COUNT(*) + 1),8)) FROM provincias);
	INSERT INTO provincias (idprovincia, iddepartamento, provincia) VALUES(_idprovincia, _iddepartamento, _provincia);
END $$


DELIMITER $$
CREATE PROCEDURE SPU_DISTRITOS_REGISTRAR
(
	IN _idprovincia		CHAR(10),
	IN _distrito		VARCHAR(70),
	IN _ubigeo			CHAR(6)
)
BEGIN
	DECLARE _iddistrito CHAR(10);
	SET _iddistrito = (SELECT CONCAT('DI',RIGHT(CONCAT('0000000000',COUNT(*) + 1),8)) FROM distritos);
	INSERT INTO distritos (iddistrito,idprovincia,distrito,ubigeo) VALUES(_iddistrito,_idprovincia,_distrito,_ubigeo);
END $$


